/** SVG path data and width (in pixels) for one line of text. */
export function pixelPath(text: string): { d: string; width: number } {
  let d = ''
  const chars = [...text.toUpperCase()]
  chars.forEach((char, index) => {
    const glyph = GLYPHS[char] ?? GLYPHS[' ']
    const x0 = index * 6
    glyph.forEach((row, y) => {
      for (let x = 0; x < row.length; x += 1) {
        if (row[x] === '#') d += `M${x0 + x} ${y}h1v1h-1z`
      }
    })
  })
  return { d, width: Math.max(1, chars.length * 6 - 1) }
}

type PixelTextProps = {
  text: string
  /**
   * Sizing: set the CSS variable `--px` (screen pixels per font pixel, a whole number keeps
   * every pixel crisp), e.g. `[--px:6px] lg:[--px:8px]`. Width and height follow from it.
   */
  className?: string
  /** Hard drop shadow offset in font pixels, drawn in `shadowColor`. */
  shadow?: number
  shadowColor?: string
  style?: CSSProperties
}

export function PixelText({ text, className, style, shadow = 0, shadowColor = 'currentColor' }: PixelTextProps) {
  const { d, width } = pixelPath(text)
  return (
    <svg
      aria-hidden="true"
      viewBox={`0 0 ${width + shadow} ${7 + shadow}`}
      className={className}
      style={{
        width: `calc(var(--px, 4px) * ${width + shadow})`,
        height: `calc(var(--px, 4px) * ${7 + shadow})`,
        ...style,
      }}
      shapeRendering="crispEdges"
      preserveAspectRatio="xMinYMid meet"
    >
      {shadow ? <path d={d} transform={`translate(${shadow} ${shadow})`} fill={shadowColor} /> : null}
      <path d={d} fill="currentColor" />
    </svg>
  )
}
